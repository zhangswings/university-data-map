def get_coords(location, region):
    if location and location in CITY_COORDS:
        return CITY_COORDS[location]
    if region and region in PROVINCE_COORDS:
        base = PROVINCE_COORDS[region]
        import random
        random.seed(hash(location or region))
        return [
            round(base[0] + random.uniform(-1.5, 1.5), 4),
            round(base[1] + random.uniform(-1.0, 1.0), 4)
        ]
    return [116.405285, 39.904989]

def main():
    with open('universities.json', 'r', encoding='utf-8') as f:
        data = json.load(f)

    for uni in data['universities']:
        coords = get_coords(uni.get('location'), uni.get('region'))
        uni['lng'] = coords[0]
        uni['lat'] = coords[1]

    with open('universities.json', 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"已为 {len(data['universities'])} 所高校添加经纬度坐标")

if __name__ == "__main__":
    main()
